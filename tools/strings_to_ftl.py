"""Writes the Rust app's Fluent files from apps/ugurugu/i18n/strings.txt.

Usage: python -X utf8 tools/strings_to_ftl.py

One message per line:

    key | English | 한국어 | 日本語 [| access] [| args=name,name]

Qt-style %1, %2 become Fluent variables named by `args`, and mnemonics (&F)
are dropped, except that `access` keeps a Korean or Japanese "(&F)" as "(F)"
for the menu titles, which Alt and the letter open. Many translations came
from the 2.2.13 Qt catalogues, which is why they are written this way.

Then writes apps/ugurugu/i18n/en.ftl, ko.ftl and ja.ftl."""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "apps", "ugurugu", "i18n")


def plain(text, args, access=False):
    text = re.sub(r"\(&(\w)\)", r"(\1)" if access else "", text).replace("&&", "\0").replace("&", "").replace("\0", "&")
    for index, name in enumerate(args, 1):
        text = text.replace(f"%{index}", "\x01" + name + "\x02")
    if "%" in re.sub(r"%%", "", text) and re.search(r"%\d", text):
        raise ValueError(f"unnamed Qt argument in {text!r}")
    return text


def value(text):
    """A Fluent value: braces and leading or trailing spaces quoted."""
    parts = [part for part in re.split(r"(\x01\w+\x02)", text) if part]
    out = []
    for index, part in enumerate(parts):
        if part.startswith("\x01"):
            out.append("{ $" + part[1:-1] + " }")
            continue
        # Fluent drops a value's outer spaces and reads a leading [ * . as
        # syntax, so those and braces are written as string literals.
        edge = (index == 0 and part[0] in " [*.") or (index == len(parts) - 1 and part[-1] == " ")
        if edge or "{" in part or "}" in part:
            out.append('{ "' + part.replace("\\", "\\\\").replace('"', '\\"') + '" }')
        else:
            out.append(part)
    return "".join(out)


def main():
    spec = os.path.join(OUT, "strings.txt")
    files = {"en": [], "ko": [], "ja": []}
    keys = set()
    with open(spec, encoding="utf-8") as lines:
        for number, line in enumerate(lines, 1):
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                for language in files:
                    files[language].append(line)
                continue
            fields = [field.strip() for field in line.split("|")]
            if len(fields) < 4:
                sys.exit(f"strings.txt:{number}: needs English, Korean and Japanese text")
            key, extra = fields[0], fields[4:]
            if key in keys:
                sys.exit(f"strings.txt:{number}: {key} is listed twice")
            keys.add(key)
            args = []
            if extra and extra[-1].startswith("args="):
                args = extra.pop()[5:].split(",")
            access = bool(extra) and extra[-1] == "access"
            if access:
                extra.pop()
            if extra:
                sys.exit(f"strings.txt:{number}: {key}: unknown field {extra[0]!r}")
            texts = dict(zip(("en", "ko", "ja"), fields[1:4]))
            for language, text in texts.items():
                files[language].append(f"{key} = {value(plain(text, args, access))}")
    header = "# Generated by tools/strings_to_ftl.py from strings.txt. Do not edit.\n\n"
    for language, entries in files.items():
        with open(os.path.join(OUT, f"{language}.ftl"), "w", encoding="utf-8", newline="\n") as out:
            out.write(header + "\n".join(entries).strip("\n") + "\n")
    print(f"{len(keys)} messages written")


if __name__ == "__main__":
    main()
